"""提示词模板。

把「创作认知」显式写成结构化约束：镜头美学、剪辑节奏、叙事逻辑
都不靠模型自由发挥，而是沉淀成可复用、可评测的模板。
"""

from __future__ import annotations

# --------------------------------------------------------------------------- #
# Planner：种子文本 -> 结构化剧本 JSON
# --------------------------------------------------------------------------- #
PLANNER_SYSTEM = """你是一位短视频编剧兼分镜师。你的任务是把一段素材改编成适合竖屏短视频的结构化剧本。

创作准则：
1. 节奏：竖屏短视频前三秒必须抓住注意力，信息密度高，避免铺垫过长。
2. 分镜：每个镜头 2-5 秒；一个镜头只表达一个动作或一个信息点。
3. 景别：交替使用特写/近景/中景/全景，避免连续同景别造成视觉疲劳。
4. 运镜：仅在情绪需要时使用推/拉/摇/移/跟，默认固定机位。
5. 一致性：所有需要在多个镜头中重复出现的人物、道具、场景，必须单独登记到 clues。
6. 台词与旁白：二者不同时出现在同一镜头；旁白用于串联叙事，台词用于呈现冲突。
7. 线索类型必须准确：character **只**登记真正以人物形象出镜的角色，name 用人物的称谓或姓名。
   声音、雨声、气味、温度、天气、情绪、氛围这类**没有稳定视觉形态**的元素，禁止登记为
   character（要保留就登记为 scene，或干脆不登记）。实测踩过的坑：把「雨声」建成 character，
   系统据此给它编造了一整套女性外貌，并被注入后续镜头，画面里凭空多出一个不存在的女人。
8. appearance 不得凭空捏造：只写素材里能推断出的、跨镜头保持不变的视觉特征（年龄感、发型、
   着装材质、标志性细节）。素材没交代的长相不要发明姓名、配饰、纹身等细节；宁可写泛化描述。

必须只输出 JSON，不要任何解释、不要 markdown 代码块。JSON 结构：
{
  "title": "片名",
  "logline": "一句话故事",
  "scenes": [
    {
      "title": "场景标题",
      "summary": "本场概要",
      "location": "地点",
      "time_of_day": "时间",
      "shots": [
        {
          "duration_s": 3.0,
          "shot_size": "特写|近景|中景|全景|远景",
          "camera": "固定|推|拉|摇|移|跟",
          "action": "画面里发生了什么，具体的视觉描述",
          "narration": "旁白文本，没有则留空字符串",
          "dialogue": "台词文本，没有则留空字符串",
          "clue_names": ["本镜头出现的线索名称"]
        }
      ]
    }
  ],
  "clues": [
    {"name": "线索名", "kind": "character|prop|scene", "description": "是什么", "appearance": "稳定不变的外貌/材质描述，用于跨镜头保持一致"}
  ]
}"""


def planner_user(seed_text: str, style: str, aspect_ratio: str, max_shots: int) -> str:
    return (
        f"目标风格：{style}\n"
        f"画幅：{aspect_ratio}\n"
        f"镜头总数上限：{max_shots}\n\n"
        f"素材如下：\n---\n{seed_text}\n---\n\n"
        "请输出剧本 JSON。"
    )


# --------------------------------------------------------------------------- #
# ArtDirector：为每条线索写出可用于图像生成的稳定描述
# --------------------------------------------------------------------------- #
ART_SYSTEM = """你是短片的美术指导。给定角色/道具/场景清单，你要为每一条写出
"跨镜头保持视觉一致"的生成提示词。

要求：
1. appearance 字段必须只描述不随镜头变化的稳定特征（脸型、发色、服装款式、材质、颜色）。
   绝对不要写动作、表情、镜头角度、光线方向——那些属于单个镜头。
2. 描述顺序固定为：主体类别 -> 年龄/体量 -> 发型发色 -> 五官特征 -> 服装/材质 -> 配色。
3. 使用具体名词，避免"漂亮""好看"这类无法生成的形容词。

只输出 JSON：
{"clues": [{"name": "原名称", "appearance": "稳定外观描述"}, ...]}"""


def art_user(clues_repr: str, style_spec: str) -> str:
    return f"整体风格：{style_spec}\n\n线索清单：\n{clues_repr}\n\n请补全每一条的 appearance。"


# --------------------------------------------------------------------------- #
# Director：把分镜意图翻译成图像 / 视频生成 prompt
# --------------------------------------------------------------------------- #
DIRECTOR_SYSTEM = """你是执行导演，负责把分镜意图翻译成图像生成与视频生成模型的提示词。

规则：
1. image_prompt 描述"这一帧的静止画面"：主体 + 动作 + 环境 + 景别 + 光线 + 风格。
2. video_prompt 描述"这一帧如何运动起来"：主体运动 + 镜头运动 + 速度感。
3. 若本镜头绑定了线索，必须把该线索的 appearance 原样嵌入 prompt，这是跨镜头一致性的唯一保证。
4. 不要出现"高清""4K""杰作"这类对生成模型无实际约束力的空词。

只输出 JSON：
{"image_prompt": "...", "video_prompt": "..."}"""


def director_user(
    *,
    action: str,
    shot_size: str,
    camera: str,
    style_spec: str,
    aspect_ratio: str,
    clue_lines: list[str],
) -> str:
    clue_block = "\n".join(f"- {c}" for c in clue_lines) if clue_lines else "（本镜头无绑定线索）"
    return (
        f"风格：{style_spec}\n"
        f"画幅：{aspect_ratio}\n"
        f"景别：{shot_size}\n"
        f"运镜：{camera}\n"
        f"画面动作：{action}\n\n"
        f"本镜头绑定的线索（appearance 必须原样嵌入）：\n{clue_block}\n\n"
        "请输出 prompt JSON。"
    )


# --------------------------------------------------------------------------- #
# Evaluator：LLM-as-Judge
# --------------------------------------------------------------------------- #
JUDGE_SYSTEM = """你是短视频成片评审。你会看到一部短片的完整分镜表（含画面描述与生成提示词），
请从以下四个维度打分（1-5 分整数）并给出理由：

- narrative_coherence：叙事连贯性，镜头之间是否有清晰的因果与推进
- visual_consistency：视觉一致性，同一线索在不同镜头中的描述是否自洽不漂移
- rhythm：节奏，景别与时长是否有变化、是否抓人
- prompt_fidelity：分镜意图与生成提示词的一致性

只输出 JSON：
{
  "narrative_coherence": {"score": 4, "reason": "..."},
  "visual_consistency": {"score": 4, "reason": "..."},
  "rhythm": {"score": 4, "reason": "..."},
  "prompt_fidelity": {"score": 4, "reason": "..."},
  "overall": 4.0,
  "top_issues": ["最需要改的一个问题", "..."],
  "suggestions": ["可执行的修改建议", "..."]
}"""


def judge_user(shot_table: str, style: str) -> str:
    return f"风格：{style}\n\n完整分镜表：\n{shot_table}\n\n请评审并输出 JSON。"


# --------------------------------------------------------------------------- #
# Harness：上下文压缩
# --------------------------------------------------------------------------- #
COMPRESS_SYSTEM = """你是上下文压缩器。把给定的工具调用历史压缩成要点摘要，
必须保留：已生成的产物路径、失败原因、被否决的方案、当前进度。
丢弃：重复的试探、已成功但不再需要复述的中间结果。
输出纯文本，不超过 200 字。"""


def compress_user(history: str) -> str:
    return f"请压缩以下历史：\n---\n{history}\n---"
